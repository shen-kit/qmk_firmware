enum custom_keycodes {
    K_EMAIL = SAFE_RANGE
};
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case K_EMAIL:
            if (record->event.pressed) {
                SEND_STRING("shenkit108@gmail.com");
            }
            return false;
        default:
            return true;
    }
}

